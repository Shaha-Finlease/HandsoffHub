CREATE TABLE IF NOT EXISTS bank_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref_no TEXT,
    bank_name TEXT,
    sheet_name TEXT,
    tx_date TEXT,
    amount NUMERIC,
    narration TEXT,
    cheque_raw TEXT,
    cheque_extracted TEXT,
    batch_date TEXT,
    status TEXT DEFAULT 'UNALLOCATED',
    claimed_by_manager TEXT,
    customer_id TEXT,
    customer_name TEXT,
    portfolio TEXT,
    caller_name TEXT,
    mode_of_pay TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Index for high speed queries
CREATE INDEX IF NOT EXISTS idx_status ON bank_transactions(status);
CREATE INDEX IF NOT EXISTS idx_manager ON bank_transactions(claimed_by_manager);

-- Enable public access for demo / anon key
ALTER TABLE bank_transactions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read" 
ON bank_transactions FOR SELECT 
TO anon 
USING (true);

CREATE POLICY "Allow public insert" 
ON bank_transactions FOR INSERT 
TO anon 
WITH CHECK (true);

CREATE POLICY "Allow public update" 
ON bank_transactions FOR UPDATE 
TO anon 
USING (true);
